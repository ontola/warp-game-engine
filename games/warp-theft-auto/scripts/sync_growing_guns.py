"""Build the small Luau gun dependency shipped in Port Meridian from Growing Guns' mods."""
import argparse
from pathlib import Path
import re

game = Path(__file__).resolve().parents[1]
source = game.parent / "growing-guns"
mods = source / "mods/base"
gun = (mods / "gun.luau").read_text(encoding="utf-8")
cards = (mods / "cards.luau").read_text(encoding="utf-8")
fields = ["damage", "fire_interval", "mag_size", "reload_time", "spread", "headshot"]
defaults = []
for name in fields:
    value, = re.findall(r"^\s*" + name + r"\s*=\s*([\d.]+),", gun, re.M)
    defaults.append(f"    {name} = {value},")
definitions = []
for name in ("shotgun", "uzi", "sniper"):
    body, = re.findall(
        r'\{ id = "' + name + r'",[^\n]*\n\s+apply = function\(w\)\n(.*?)\n\t\tend \},',
        cards, re.S,
    )
    definitions.append(f"    {name} = function(w)\n{body}\n    end,")

module = """-- Generated by scripts/sync_growing_guns.py from Growing Guns' base gun and cards.
local max, deg_to_rad, Color = math.max, math.rad, vector.create
local function lerp(a,b,t) return a+(b-a)*t end
local gun = {
""" + "\n".join(defaults) + "\n}\nlocal cards = {\n" + "\n".join(definitions) + "\n}\nreturn {gun=gun, cards=cards}\n"
exports = {
    game / "growing_guns_data.module.luau": module.encode("utf-8"),
    game / "sounds/growing_guns_shot.luau": (source / "sounds/shot.luau").read_bytes(),
    game / "sounds/arcade_launcher.luau": (source / "sounds/grenade_launch.luau").read_bytes(),
}
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
check = parser.parse_args().check
for path, payload in exports.items():
    payload = payload.replace(b"\r\n", b"\n")
    if check:
        if not path.exists() or path.read_bytes().replace(b"\r\n", b"\n") != payload:
            raise SystemExit(f"{path.name} differs from the Growing Guns export")
    else:
        path.write_bytes(payload)
