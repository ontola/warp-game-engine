//! The six biomes of a run, one level each (Arena.BIOMES). Colours are
//! Godot colours (sRGB), as the Godot game wrote them.

use crate::el::El;

pub type Rgb = [f32; 3];

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum WallStyle {
    Masonry,
    Ossuary,
    Rock,
    Castle,
    Cliff,
}

#[derive(Clone, Debug)]
pub struct Biome {
    pub id: &'static str,
    pub name: &'static str,
    pub moss: f32,
    pub moss_c: Rgb,
    /// The props of each of the three zones along the level.
    pub zones: [&'static [&'static str]; 3],
    pub floor_a: Rgb,
    pub floor_b: Rgb,
    pub tiles: f32,
    pub wet: f32,
    pub wall: Rgb,
    pub fog: Rgb,
    pub ambient: Rgb,
    pub moon: Rgb,
    pub moon_energy: f32,
    pub mist: f32,
    pub mist_c: Rgb,
    pub props: &'static [&'static str],
    /// Monster kinds and how many of each go in a wave's pool.
    pub enemies: &'static [(&'static str, u32)],
    pub boss: &'static str,
    /// Permanent fields laid about the level, a set every 9 m of its length.
    pub fields: &'static [El],
    pub path_style: i32,
    pub path_a: Rgb,
    pub path_b: Rgb,
    /// "nave": a built biome with a straight middle stretch.
    pub nave: bool,
    pub corridor: bool,
    pub outside: &'static [&'static str],
    pub wall_style: WallStyle,
    pub wall_props: &'static [&'static str],
    pub wall_every: f32,
    pub isles: bool,
    pub low_walls: bool,
    pub water_props: &'static [&'static str],
    pub density: f32,
    pub outside_lava: bool,
}

